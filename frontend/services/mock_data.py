def _score_formation(formation, profil_academique):
    from state import get_centre_interet_effectif

    notes = profil_academique.get("notes", {})
    centre_interet = get_centre_interet_effectif(profil_academique)
    score = 40.0
    if formation["id"] == "igglia" and "Informatique" in centre_interet:
        score += 45
    if formation["id"] == "esiia" and "Gestion" in centre_interet:
        score += 45
    if formation["id"] == "imticia" and "Réseaux" in centre_interet:
        score += 45
    if formation["id"] == "isaia" and any(mot in centre_interet for mot in ("Mathématiques", "Sciences", "Statistiques", "Intelligence")):
        score += 45
    score += (notes.get("Mathématiques", 12) - 10) * 2
    return max(1.0, min(score, 99.0))


def generer_recommandation_academique(profil_academique):
    scores = [(formation, _score_formation(formation, profil_academique)) for formation in FORMATIONS]
    scores.sort(key=lambda item: item[1], reverse=True)
    total = sum(score for _, score in scores) or 1.0
    top3 = [
        {"rang": rang, "code": formation["nom"], "score": round(score / total * 100, 1)}
        for rang, (formation, score) in enumerate(scores, start=1)
    ]
    from state import get_centre_interet_effectif

    centre_interet = get_centre_interet_effectif(profil_academique)
    meilleure_note = max(profil_academique.get("notes", {}), key=profil_academique.get("notes", {}).get, default="")
    return {
        "filiere_principale": {"code": top3[0]["code"], "score": top3[0]["score"]},
        "top3": top3,
        "justifications": [
            f"Votre intérêt pour {centre_interet.lower()} correspond au cœur de ce parcours.",
            f"Vos notes en {meilleure_note} sont un atout significatif." if meilleure_note else "Vos résultats scolaires sont cohérents avec ce parcours.",
            "Ce parcours offre des débouchés alignés sur vos objectifs déclarés.",
        ],
        "origine": "Modèle ML (donnée de démonstration)",
    }


